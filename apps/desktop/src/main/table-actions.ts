import { ctxForObject, makeError, runWrite, type Dialect, type TableStructure, type WriteResult } from '@earthql/core';
import { tableActionOptions, type TableActionRequest } from '../shared/table-actions';
import type { SessionManager } from './sessions';

export function buildTableAction(dialect: Dialect, structure: TableStructure, request: TableActionRequest): { statements: string[]; cleanupSql?: string } {
  const supported = tableActionOptions(dialect.driver);
  if (structure.kind !== 'table') throw makeError('unsupported', 'This action requires a base table.');
  if (request.ignoreForeignKeys && !supported.ignoreForeignKeys) throw makeError('unsupported', 'Disabling foreign key checks is not supported by this database.');
  if (request.cascade && !supported.cascade) throw makeError('unsupported', 'CASCADE is not supported by this database.');
  if (request.restartIdentity && !supported.restartIdentity && !supported.resetsIdentity) throw makeError('unsupported', 'Restart identity is not supported by this database.');
  const source = dialect.qualify(request.object);
  if (request.action === 'truncate') return { statements: [`TRUNCATE TABLE ${source}${dialect.driver === 'postgres' ? request.restartIdentity ? ' RESTART IDENTITY' : ' CONTINUE IDENTITY' : ''}${request.cascade ? ' CASCADE' : ''}`] };
  if (request.action === 'delete') return { statements: [`DROP TABLE ${source}${request.cascade ? ' CASCADE' : ''}`] };
  if (request.action !== 'clone') throw makeError('config', 'Unknown table action.');
  const name = request.cloneName.trim();
  if (!name || name.includes('\0') || name === request.object.name) throw makeError('config', 'Enter a different, non-empty name for the cloned table.');
  if (structure.columnsStatus.state !== 'ok') throw makeError('permission', 'Column metadata is required to clone a table.');
  const target = dialect.qualify({ ...request.object, name });
  const columns = structure.columns.filter((column) => !column.isGenerated || column.isIdentity);
  const list = columns.map((column) => dialect.quoteIdent(column.name)).join(', ');
  if (dialect.driver === 'mysql') {
    if (request.copyData && !columns.length) throw makeError('unsupported', 'There are no writable columns to clone.');
    return { statements: [`CREATE TABLE ${target} LIKE ${source}`, ...(request.copyData ? [`INSERT INTO ${target} (${list}) SELECT ${list} FROM ${source}`] : [])], cleanupSql: `DROP TABLE ${target}` };
  }
  if (dialect.driver === 'postgres') {
    const statements = [`CREATE TABLE ${target} (LIKE ${source} INCLUDING ALL)`];
    const sequences = columns.filter((column) => column.isIdentity || /\bnextval\s*\(/i.test(column.defaultValue ?? ''));
    for (const column of sequences.filter((column) => !column.isIdentity)) {
      statements.push(`ALTER TABLE ${target} ALTER COLUMN ${dialect.quoteIdent(column.name)} DROP DEFAULT`);
      statements.push(`ALTER TABLE ${target} ALTER COLUMN ${dialect.quoteIdent(column.name)} ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    if (request.copyData) {
      if (!columns.length) throw makeError('unsupported', 'There are no writable columns to clone.');
      statements.push(`INSERT INTO ${target} (${list}) OVERRIDING SYSTEM VALUE SELECT ${list} FROM ${source}`);
      for (const column of sequences) statements.push(`SELECT setval(pg_get_serial_sequence(${dialect.stringLiteral(target)}, ${dialect.stringLiteral(column.name)}), MAX(${dialect.quoteIdent(column.name)}), true) FROM ${target} HAVING MAX(${dialect.quoteIdent(column.name)}) IS NOT NULL`);
    }
    return { statements };
  }
  if (dialect.driver === 'mssql') return { statements: [`SELECT ${request.copyData ? '' : 'TOP (0) '}* INTO ${target} FROM ${source}`] };
  return { statements: [`CREATE TABLE ${target} AS SELECT * FROM ${source}${request.copyData ? '' : ' WHERE 1 = 0'}`] };
}

export async function executeTableAction(sessions: SessionManager, profileId: string, request: TableActionRequest): Promise<WriteResult> {
  const started = Date.now();
  const { conn } = sessions.get(profileId);
  try {
    const structure = await sessions.structure(profileId, request.object, true);
    const batch = buildTableAction(conn.dialect, structure, request);
    if (conn.executeTableStatements) await conn.executeTableStatements(request.object, batch.statements, { disableForeignKeys: request.ignoreForeignKeys, cleanupSql: batch.cleanupSql });
    else {
      if (batch.statements.length !== 1 || request.ignoreForeignKeys) throw makeError('unsupported', 'This connection cannot run the requested action.');
      const result = await runWrite(conn, { sql: batch.statements[0], params: [], errors: [], warnings: [], target: conn.dialect.displayTarget(request.object) }, ctxForObject(request.object));
      return result;
    }
    return { status: 'ok', durationMs: Date.now() - started };
  } catch (error) {
    const info = sessions.errorFor(profileId, error);
    const uncertain = ['network', 'timeout', 'outcome_unknown'].includes(info.category);
    return { status: uncertain ? 'outcome_unknown' : 'error', error: uncertain ? { ...info, category: 'outcome_unknown', hint: 'Refresh the table/schema to check the result before retrying.' } : info, durationMs: Date.now() - started };
  }
}
