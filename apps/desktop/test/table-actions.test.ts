import { describe, expect, it, vi } from 'vitest';
import { mysqlDialect, mysqlDriver } from '@earthql/driver-mysql';
import { postgresDialect, postgresDriver } from '@earthql/driver-postgres';
import { mssqlDialect } from '@earthql/driver-mssql';
import type { TableStructure } from '@earthql/core';
import { buildTableAction, executeTableAction } from '../src/main/table-actions';
import type { TableActionRequest } from '../src/shared/table-actions';
import type { SessionManager } from '../src/main/sessions';

const object = { database: 'demo', schema: 'public', name: 'source' };
const structure = { object, kind: 'table', columnsStatus: { state: 'ok' }, columns: [{ name: 'id', type: 'int', kind: 'number', defaultValue: null }, { name: 'name', type: 'text', kind: 'text', defaultValue: null }] } as TableStructure;
const request: TableActionRequest = { action: 'clone', object, cloneName: 'source_clone', copyData: true, restartIdentity: false, ignoreForeignKeys: false, cascade: false };

describe('table action statements', () => {
  it('quotes clone names and only copies data when requested', () => {
    const result = buildTableAction(mysqlDialect, structure, { ...request, cloneName: 'new`; DROP TABLE source; --' });
    expect(result.statements).toHaveLength(2);
    expect(result.statements[0]).toContain('`new``; DROP TABLE source; --`');
    expect(result.statements[1]).toContain('INSERT INTO');
    expect(buildTableAction(mysqlDialect, structure, { ...request, copyData: false }).statements).toHaveLength(1);
  });
  it('uses DROP TABLE for Delete and TRUNCATE TABLE for Truncate', () => {
    expect(buildTableAction(mysqlDialect, structure, { ...request, action: 'delete' }).statements).toEqual(['DROP TABLE `demo`.`source`']);
    expect(buildTableAction(postgresDialect, structure, { ...request, action: 'truncate', restartIdentity: true, cascade: true }).statements[0]).toContain('RESTART IDENTITY CASCADE');
    expect(buildTableAction(postgresDialect, structure, { ...request, action: 'truncate' }).statements[0]).toContain('CONTINUE IDENTITY');
  });
  it('rejects invalid options, views and reusing the source name', () => {
    expect(() => buildTableAction(mysqlDialect, structure, { ...request, cascade: true })).toThrow();
    expect(() => buildTableAction(postgresDialect, structure, { ...request, ignoreForeignKeys: true })).toThrow();
    expect(() => buildTableAction(mysqlDialect, structure, { ...request, cloneName: 'source' })).toThrow();
    expect(() => buildTableAction(mysqlDialect, { ...structure, kind: 'view' }, request)).toThrow();
  });
  it('creates independent PostgreSQL serial sequences and advances them after copying', () => {
    const serial = { ...structure, columns: [{ ...structure.columns[0], defaultValue: "nextval('source_id_seq'::regclass)" }] };
    const sql = buildTableAction(postgresDialect, serial, request).statements.join(';');
    expect(sql).toContain('ADD GENERATED BY DEFAULT AS IDENTITY');
    expect(sql).toContain('OVERRIDING SYSTEM VALUE');
    expect(sql).toContain('setval(pg_get_serial_sequence');
  });
  it('uses SELECT INTO for SQL Server column/data clones', () => {
    expect(buildTableAction(mssqlDialect, structure, { ...request, copyData: false }).statements[0]).toContain('SELECT TOP (0) * INTO');
  });
});

describe('pinned database session handling', () => {
  const profile = { id: 'p', name: 'test', driver: 'mysql', host: 'localhost', port: 3306, database: 'demo', user: 'test', tls: { mode: 'disable' }, env: { name: 'Local', color: '#888' }, createdAt: 0, updatedAt: 0 } as const;
  it('restores the original MySQL FK setting and cleans up failed clones on the same session', async () => {
    const queries: string[] = [];
    const query = vi.fn(async (sql: string) => {
      queries.push(sql);
      if (sql.startsWith('SELECT @@')) return [[{ fk: 1 }]];
      if (sql.startsWith('INSERT')) throw Error('copy failed');
      return [[]];
    });
    const release = vi.fn(), destroy = vi.fn();
    const connection = mysqlDriver.connect(profile, {});
    (connection as any).acquire = async () => ({ promise: () => ({ query }), release, destroy });
    await expect(connection.executeTableStatements!(object, ['CREATE TABLE x LIKE y', 'INSERT INTO x SELECT * FROM y'], { disableForeignKeys: true, cleanupSql: 'DROP TABLE x' })).rejects.toThrow('copy failed');
    expect(queries).toEqual(['USE `demo`', 'SELECT @@SESSION.foreign_key_checks AS fk', 'SET SESSION FOREIGN_KEY_CHECKS = 0', 'CREATE TABLE x LIKE y', 'INSERT INTO x SELECT * FROM y', 'DROP TABLE x', 'SET SESSION FOREIGN_KEY_CHECKS = 1']);
    expect(release).toHaveBeenCalledOnce(); expect(destroy).not.toHaveBeenCalled();
  });
  it('never drops an existing target when CREATE fails', async () => {
    const queries: string[] = [];
    const connection = mysqlDriver.connect(profile, {});
    (connection as any).acquire = async () => ({ promise: () => ({ query: async (sql: string) => { queries.push(sql); if (sql.startsWith('CREATE')) throw Error('Already exists'); } }), release: vi.fn(), destroy: vi.fn() });
    await expect(connection.executeTableStatements!(object, ['CREATE TABLE x LIKE y', 'INSERT INTO x SELECT * FROM y'], { disableForeignKeys: false, cleanupSql: 'DROP TABLE x' })).rejects.toThrow();
    expect(queries).not.toContain('DROP TABLE x');
  });
  it('rolls PostgreSQL clone changes back on the pinned client if copying fails', async () => {
    const connection = postgresDriver.connect({ ...profile, driver: 'postgres', port: 5432 }, {});
    const queries: string[] = [];
    const release = vi.fn();
    (connection as any).acquire = async () => ({ query: async (sql: string) => { queries.push(sql); if (sql === 'copy') throw Error('failed'); }, release });
    await expect(connection.executeTableStatements!(object, ['create', 'copy'], { disableForeignKeys: false })).rejects.toThrow();
    expect(queries).toEqual(['BEGIN', 'create', 'copy', 'ROLLBACK']); expect(release).toHaveBeenCalledWith(false);
  });
  it('classifies a network failure as an unknown write outcome', async () => {
    const sessions = { get: () => ({ conn: { dialect: mysqlDialect, executeTableStatements: async () => { throw Error('network'); } } }), structure: async () => structure, errorFor: () => ({ category: 'network', message: 'Lost connection' }) } as unknown as SessionManager;
    expect(await executeTableAction(sessions, 'p', { ...request, action: 'delete' })).toMatchObject({ status: 'outcome_unknown', error: { category: 'outcome_unknown' } });
  });
});
